// Builds video-prompt-director.md, the single-file edition, from SKILL.md.
// `--check` fails when the committed file is out of date instead of rewriting it.
import { readFileSync, writeFileSync } from "node:fs";

const read = (file) => readFileSync(file, "utf8").replace(/\r\n/g, "\n");

export function buildSingleFile() {
  const skill = read("plugins/video-prompt-director/skills/video-prompt-director/SKILL.md");
  const version = read("plugins/video-prompt-director/skills/video-prompt-director/VERSION").trim();
  const body = skill.slice(skill.indexOf("\n---\n", 4) + 5).trim();
  const withoutMap = body.slice(0, body.indexOf("\n## Reference map")).trim();

  return `<!-- Generated by scripts/build-single-file.mjs from plugins/video-prompt-director/skills/video-prompt-director/SKILL.md. Edit the source, then run npm run build:single. -->
# video-prompt-director (single-file edition, v${version})

Paste this file into a chat or a project's instructions when you can't install the full skill. It carries the workflows and the core rules. The full skill in [plugins/video-prompt-director/skills/video-prompt-director](plugins/video-prompt-director/skills/video-prompt-director) adds the reference guides, the model files and the examples that the text below mentions. Without them, apply the rules here directly, and do not state any video model's limits, supported inputs or prices unless the user gives them to you.

${withoutMap.replace(/^# Video Prompt Director\s*/, "")}
`;
}

const out = buildSingleFile();
if (process.argv.includes("--check")) {
  if (read("video-prompt-director.md") !== out) {
    console.error("video-prompt-director.md is out of date. Run: npm run build:single");
    process.exit(1);
  }
  console.log("video-prompt-director.md is up to date.");
} else {
  writeFileSync("video-prompt-director.md", out);
  console.log("Wrote video-prompt-director.md");
}
